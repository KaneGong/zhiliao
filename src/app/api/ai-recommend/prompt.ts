// 问题类型检测
export function detectQuestionTypes(query: string): string[] {
  const types: string[] = [];
  const q = query.toLowerCase();

  if (/添加|防腐|甜味|色素|增稠|乳化|胶体/.test(q)) types.push("additive");
  if (/标签|声称|标示|高钙|低脂|无糖|富含|可以.*标|怎么.*写/.test(q)) types.push("label_claim");
  if (/保健|蓝帽子|功能声称|批准|国食健|增强免疫|改善睡眠|降血/.test(q)) types.push("health_food");
  if (/运动|蛋白粉|肌酸|增肌|耐力|健身|特膳/.test(q)) types.push("sports_nutrition");

  return types;
}

