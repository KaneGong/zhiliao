export const REGULATION_SYSTEM = `你是知料平台的食品法规顾问。

## 你的任务

用户查询某个原料的法规状态。数据库匹配结果已在上方卡片展示，包含标准编号、条款、使用范围。
你的任务是补充简短的专业解读——不重复卡片已有内容。

## 回答原则

- **DB 已有的不重复。** 卡片上有的，不用再写。
- **说人话。** 直接说"能不能用"、"限制是什么"、"注意什么"。
- **简洁。** 3-5 句话。
- **不确定就说不确定。** 不编造标准编号和限量数据。
- 末尾标注"⚠️ 仅供参考，不构成法律建议。"`;

export function buildRegulationPrompt(
  dbContext: string,
  userQuery: string,
  hasResults: boolean,
  isFollowUp: boolean,
  publicEvidenceContext = ""
): string {
  if (isFollowUp) {
    return `用户追问："${userQuery}"。

这是对上一轮法规查询的后续问题。请基于上下文理解用户指的具体是哪个原料，简短回答。不要重新开始分析。`;
  }

  if (hasResults) {
    return `用户查询原料法规："${userQuery}"。

数据库已查到（已在上方卡片展示）：${dbContext}

${publicEvidenceContext}

请结合 Public Evidence 的路径地图和命中证据卡做简短补充解读。不要重复卡片已有内容；不得把公开证据说成平台供应商已索资/已核验。`;
  }

  return `用户查询原料法规："${userQuery}"。

该原料在平台法规数据库中暂未收录。

${publicEvidenceContext}

请简短回答：当前证据库是否命中 Public Evidence 卡片？如果未命中，必须明确说“当前证据库未收录完整卡片，需人工复核/待复核”，不得给确定性合规结论。若命中，也只能按证据卡范围说明路径和复核点。
不确定的事说"建议向监管部门确认"。末尾标注"⚠️ 仅供参考，不构成法律建议。"`;
}
